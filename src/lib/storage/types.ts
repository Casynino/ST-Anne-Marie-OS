/**
 * File storage boundary. Documents are stored under unguessable keys and are only ever served through
 * permission-checked, audited routes — never through a public URL.
 */
export interface FileStorage {
  readonly name: string;
  put(key: string, body: Buffer, meta: { contentType: string }): Promise<void>;
  get(key: string): Promise<Buffer>;
  delete(key: string): Promise<void>;
  /** Streams an object, or a byte range of it (inclusive), without loading it into memory. `size` is the size of the whole object. */
  stream(key: string, range?: { start: number; end: number }): Promise<{ body: ReadableStream<Uint8Array>; size: number }>;
}

/** Keys are generated by the server; this is a safety net against path tricks if that ever changes. */
export const SAFE_KEY = /^[A-Za-z0-9][A-Za-z0-9/_.-]{0,200}$/;
export function assertSafeKey(key: string) {
  if (!SAFE_KEY.test(key) || key.includes("..") || key.includes("//")) throw new Error("Unsafe storage key");
}
